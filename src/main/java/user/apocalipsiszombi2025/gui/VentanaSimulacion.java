    // === MÉTODOS PARA HUMANOS ===
    public void crearLabelHumano(String humanoID) {
        JLabel label = new JLabel(humanoID);
        label.setOpaque(true);
        label.setBackground(new Color(0, 102, 204)); // azul
        label.setForeground(Color.WHITE);
        label.setBorder(BorderFactory.createLineBorder(Color.BLACK));
        label.setHorizontalAlignment(SwingConstants.CENTER);
        label.setPreferredSize(new Dimension(60, 30));

        humanoLabels.put(humanoID, label);

        SwingUtilities.invokeLater(() -> {
            getPanelZonaComun().add(label);
            getPanelZonaComun().revalidate();
            getPanelZonaComun().repaint();
        });
    }

    public void moverLabelHumano(String id, JPanel destino) {
        JLabel label = humanoLabels.get(id);
        if (label == null) return;

        removerDeTodosLosPaneles(label);

        SwingUtilities.invokeLater(() -> {
            destino.add(label);
            destino.revalidate();
            destino.repaint();
        });
    }

    public void eliminarLabelHumano(String id) {
        JLabel label = humanoLabels.remove(id);
        if (label != null) {
            removerDeTodosLosPaneles(label);
            repaint();
        }
    }

    // === MÉTODOS PARA ZOMBIS ===
    public void crearLabelZombi(String id) {
        JLabel label = new JLabel(id);
        label.setOpaque(true);
        label.setBackground(new Color(102, 0, 102)); // morado
        label.setForeground(Color.WHITE);
        label.setBorder(BorderFactory.createLineBorder(Color.BLACK));
        label.setHorizontalAlignment(SwingConstants.CENTER);
        label.setPreferredSize(new Dimension(60, 30));

        zombiLabels.put(id, label);

        SwingUtilities.invokeLater(() -> {
            getPanelZonaInsegura(0).add(label); // por defecto zona 0
            getPanelZonaInsegura(0).revalidate();
            getPanelZonaInsegura(0).repaint();
        });
    }

    public void eliminarLabelZombi(String id) {
        JLabel label = zombiLabels.remove(id);
        if (label != null) {
            removerDeTodosLosPaneles(label);
            repaint();
        }
    }

    // === LIMPIEZA ===
    private void removerDeTodosLosPaneles(JLabel label) {
        getPanelZonaComun().remove(label);
        getPanelZonaComedor().remove(label);
        getPanelZonaDescanso().remove(label);

        for (int i = 0; i < 4; i++) {
            getPanelTunel(i).remove(label);
            getPanelZonaInsegura(i).remove(label);
        }
    }

    // === GETTERS DE SUBZONAS ===
    public JPanel getPanelZonaInsegura(int id) {
        return switch (id) {
            case 0 -> panelZonasInseguras;
            case 1 -> panelZonasInseguras1;
            case 2 -> panelZonasInseguras2;
            case 3 -> panelZonasInseguras3;
            default -> throw new IllegalArgumentException("Zona insegura no válida: " + id);
        };
    }

    public JPanel getPanelTunel(int id) {
        return switch (id) {
            case 0 -> panelTuneles;
            case 1 -> panelTuneles1;
            case 2 -> panelTuneles2;
            case 3 -> panelTuneles3;
            default -> throw new IllegalArgumentException("Túnel no válido: " + id);
        };
    }

